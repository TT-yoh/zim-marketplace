// scripts/local-env.mjs
// After `npx supabase start`, point the web app and edge functions at the LOCAL stack:
//   client/.env.localdb          used by `npm run dev:local` (vite --mode localdb)
//   supabase/functions/.env.local used by `npm run functions:local`
// Both files are git-ignored. The live project's client/.env is never touched.
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

let raw;
try {
    raw = execSync('npx supabase status -o env', { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
} catch (e) {
    console.error('Local Supabase is not running. Start it first with: npm run local:start');
    process.exit(1);
}

const env = Object.fromEntries(
    raw.split(/\r?\n/)
        .map(line => line.match(/^([A-Z_]+)="?(.*?)"?$/))
        .filter(Boolean)
        .map(m => [m[1], m[2]])
);

const apiUrl = env.API_URL;
const anonKey = env.ANON_KEY || env.PUBLISHABLE_KEY;
if (!apiUrl || !anonKey || !/^https?:\/\/(127\.0\.0\.1|localhost)/.test(apiUrl)) {
    console.error('Could not read a local API URL and anon key from `supabase status`. Got:', Object.keys(env).join(', '));
    process.exit(1);
}

fs.writeFileSync(path.join(root, 'client', '.env.localdb'), [
    '# Generated by scripts/local-env.mjs: local Supabase stack only',
    `VITE_SUPABASE_URL=${apiUrl}`,
    `VITE_SUPABASE_ANON_KEY=${anonKey}`,
    '',
].join('\n'));

fs.writeFileSync(path.join(root, 'supabase', 'functions', '.env.local'), [
    '# Generated by scripts/local-env.mjs: local edge functions only',
    '# Mock Paynow for everyone locally (no real keys); orders settle in the XTS test currency',
    'PAYMENT_MOCK_MODE=all',
    'ALLOWED_ORIGINS=http://localhost:5173,http://127.0.0.1:5173',
    'FRONTEND_URL=http://localhost:5173',
    '',
].join('\n'));

console.log(`Local stack ready:
  App (npm run dev:local) -> ${apiUrl}
  Studio                   -> ${env.STUDIO_URL || 'http://127.0.0.1:54323'}
  Email inbox              -> ${env.INBUCKET_URL || env.MAILPIT_URL || 'http://127.0.0.1:54324'}
  Test accounts            -> see supabase/seed.sql (password: zimmarket-local-dev)`);
